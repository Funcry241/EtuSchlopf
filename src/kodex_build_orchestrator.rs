fn parse_feedback_observable_sink_allowlist(
    path: &Path,
    text: &str,
) -> Result<BTreeMap<String, String>, String> {
    let mut lines = text.lines();
    if lines.next() != Some("# EtuSchlopf feedback observable sink allowlist v1")
        || lines.next() != Some("path\trole")
    {
        return Err(format!(
            "FEEDBACK OBSERVABLE SINK ALLOWLIST SCHEMA REGRESSION: {} has no exact v1 header.",
            path.display()
        ));
    }

    let mut rows = BTreeMap::new();
    for (line_index, line) in lines.enumerate() {
        if line.trim().is_empty() {
            continue;
        }
        let Some((sink_path, role)) = line.split_once('\t') else {
            return Err(format!(
                "FEEDBACK OBSERVABLE SINK ALLOWLIST PARSE ERROR: {} line {} has no tab separator.",
                path.display(),
                line_index + 3
            ));
        };
        if sink_path.is_empty()
            || role.is_empty()
            || sink_path.contains('\\')
            || sink_path.starts_with('/')
            || sink_path.contains("..")
        {
            return Err(format!(
                "FEEDBACK OBSERVABLE SINK ALLOWLIST PATH ERROR: {} line {} is not a normalized closed path/role row.",
                path.display(),
                line_index + 3
            ));
        }
        if rows.insert(sink_path.to_string(), role.to_string()).is_some() {
            return Err(format!(
                "FEEDBACK OBSERVABLE SINK ALLOWLIST DUPLICATE: {} contains path {sink_path:?} more than once.",
                path.display()
            ));
        }
    }
    Ok(rows)
}

fn parse_kodex_boundary_adversarial_matrix(
    path: &Path,
    text: &str,
) -> Result<BTreeMap<String, (String, String)>, String> {
    let mut lines = text.lines();
    if lines.next() != Some("# EtuSchlopf kodex boundary adversarial matrix v2")
        || lines.next() != Some("attack_id\tdefense\texpected")
    {
        return Err(format!(
            "KODEX BOUNDARY ADVERSARIAL MATRIX SCHEMA REGRESSION: {} has no exact v2 header.",
            path.display()
        ));
    }
    let mut rows = BTreeMap::new();
    for (line_index, line) in lines.enumerate() {
        if line.trim().is_empty() {
            continue;
        }
        let mut fields = line.split('\t');
        let attack = fields.next().unwrap_or_default();
        let defense = fields.next().unwrap_or_default();
        let expected = fields.next().unwrap_or_default();
        if attack.is_empty()
            || defense.is_empty()
            || expected != "blocked"
            || fields.next().is_some()
            || !attack
                .bytes()
                .all(|byte| byte.is_ascii_lowercase() || byte == b'_')
            || !defense
                .bytes()
                .all(|byte| byte.is_ascii_lowercase() || byte == b'_')
        {
            return Err(format!(
                "KODEX BOUNDARY ADVERSARIAL MATRIX ROW ERROR: {} line {} is not a normalized closed attack row.",
                path.display(),
                line_index + 3
            ));
        }
        if rows
            .insert(
                attack.to_string(),
                (defense.to_string(), expected.to_string()),
            )
            .is_some()
        {
            return Err(format!(
                "KODEX BOUNDARY ADVERSARIAL MATRIX DUPLICATE: {} contains attack {attack:?} more than once.",
                path.display()
            ));
        }
    }
    Ok(rows)
}

fn read_baseline(path: &Path) -> Result<BTreeMap<String, BaselineRow>, String> {
    let text = fs::read_to_string(path).map_err(|error| error.to_string())?;
    let mut rows = BTreeMap::new();
    for (line_index, line) in text.lines().enumerate() {
        let trimmed = line.trim();
        if trimmed.is_empty() || trimmed.starts_with('#') {
            continue;
        }
        let columns: Vec<&str> = line.split('\t').collect();
        if columns.len() != 3 {
            return Err(format!(
                "{}:{} expected 3 tab-separated columns: key, owner, decision",
                path.display(),
                line_index + 1
            ));
        }
        let key = columns[0].trim().to_string();
        if key.is_empty() {
            return Err(format!("{}:{} empty key", path.display(), line_index + 1));
        }
        let row = BaselineRow {
            owner: columns[1].trim().to_string(),
            decision: columns[2].trim().to_string(),
        };
        if rows.insert(key.clone(), row).is_some() {
            return Err(format!(
                "{}:{} duplicate key {key}",
                path.display(),
                line_index + 1
            ));
        }
    }
    Ok(rows)
}


